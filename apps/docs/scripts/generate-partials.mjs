#!/usr/bin/env node
/**
 * Writes the docs partials that are read off the code, so no one types them by hand:
 *
 * - docs/_partials/chat-tokens.mdx: every `--wa-chat-*` token of packages/chat/src/chat.css, its light and dark
 *   default and the 0.4.0 name it replaces (the chat theming page and the `ChatTheme` reference include it);
 * - docs/_partials/testing-reference.mdx: every page of docs/reference/testing with its one-line description (the
 *   testing CI page includes it).
 *
 *   node scripts/generate-partials.mjs          # write them
 *   node scripts/generate-partials.mjs --check  # fail when one is stale (run by this app's `test`, so by pnpm check)
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "../../..");
const check = process.argv.includes("--check");

const HEADER = "{/* Generated by apps/docs/scripts/generate-partials.mjs from the code: do not edit by hand. */}\n\n";

// ---------- 1. chat tokens ----------

/** The declarations of the first rule whose selector list is exactly `selector`. */
function block(css, selector) {
  const at = css.indexOf(`${selector} {`);
  if (at < 0) throw new Error(`chat.css: no rule "${selector}"`);
  const body = css.slice(css.indexOf("{", at) + 1, css.indexOf("\n}", at));
  const out = new Map();
  for (const m of body.matchAll(/^\s*(--wa-chat-[\w-]+):\s*([^;]+);/gm)) out.set(m[1], m[2].trim());
  return out;
}

/** `var(--name, fallback)` → [name, fallback], splitting at the first top-level comma. */
function splitVar(value) {
  const m = value.match(/^var\((--[\w-]+),\s*([\s\S]*)\)$/);
  if (!m) return null;
  return [m[1], m[2].trim()];
}

function chatTokens() {
  const css = readFileSync(join(repo, "packages/chat/src/chat.css"), "utf8");
  const root = block(css, ".wa-chat");
  const dark = block(css, '[data-theme="dark"] .wa-chat,\n.wa-chat[data-theme="dark"]');
  const shown = (v) => `\`${v.replace(/\|/g, "\\|")}\``;
  const rows = [];
  for (const [name, value] of root) {
    if (!name.startsWith("--wa-chat--") || name === "--wa-chat--dir" || name.startsWith("--wa-chat--x-")) continue;
    const parts = splitVar(value);
    if (!parts) continue;
    const [publicName, fallback] = parts;
    let light = fallback;
    let night = "";
    let old = "";
    const ref = splitVar(fallback) ?? (fallback.match(/^var\((--[\w-]+)\)$/) ? [fallback.slice(4, -1), ""] : null);
    if (ref && !ref[1] && root.has(ref[0]) && !ref[0].startsWith("--wa-chat--")) {
      // the default is a 0.4.0 name: show that name's own values
      old = ref[0];
      light = root.get(old);
      night = dark.get(old) ?? "";
    } else if (ref && !ref[1] && ref[0].startsWith("--wa-chat--")) {
      light = `follows \`${ref[0].replace("--wa-chat--", "--wa-chat-")}\``;
    }
    const cell = (v) => (!v ? "" : v.startsWith("follows") ? v : shown(v));
    rows.push(`| \`${publicName}\` | ${cell(light)} | ${cell(night)} | ${old ? `\`${old}\`` : ""} |`);
  }
  // the two tokens the root rule uses directly (no resolved copy)
  rows.push(`| \`--wa-chat-z\` | ${shown(root.get("--wa-chat-z"))} |  | \`--wa-chat-z\` |`);
  return `${HEADER}| Variable | Default | Dark default | 0.4.0 name |\n|---|---|---|---|\n${rows.join("\n")}\n`;
}

// ---------- 2. testing reference ----------

function testingReference() {
  const dir = join(repo, "docs/reference/testing");
  const rows = [];
  for (const file of readdirSync(dir)
    .filter((f) => f.endsWith(".md") && f !== "README.md")
    .sort()) {
    const text = readFileSync(join(dir, file), "utf8");
    const heading = text.match(/^# (.+)$/m)?.[1] ?? file;
    // a heading that is a phrase ("Page helpers") reads as words, not code
    const title = /^`[^`]* [^`]*`$/.test(heading) ? heading.slice(1, -1) : heading;
    const description = text.match(/^description:\s*"?(.*?)"?\s*$/m)?.[1] ?? "";
    rows.push(`| [${title}](/reference/testing/${file.replace(/\.md$/, "")}) | ${description.replace(/\|/g, "\\|")} |`);
  }
  return `${HEADER}| API | What it is |\n|---|---|\n${rows.join("\n")}\n`;
}

// ---------- write or check ----------

const outputs = [
  [join(repo, "docs/_partials/chat-tokens.mdx"), chatTokens()],
  [join(repo, "docs/_partials/testing-reference.mdx"), testingReference()],
];
let stale = 0;
for (const [path, text] of outputs) {
  let current = "";
  try {
    current = readFileSync(path, "utf8");
  } catch {}
  if (current === text) continue;
  if (check) {
    console.error(`${path.slice(repo.length + 1)} is stale: run node apps/docs/scripts/generate-partials.mjs`);
    stale++;
  } else writeFileSync(path, text);
}
if (stale) process.exit(1);
if (check) console.log("partials: up to date");
